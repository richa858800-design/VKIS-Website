-- Run this in Supabase Dashboard > SQL Editor.
create table if not exists public.admissions (
  id bigint generated by default as identity primary key,
  student_name text not null,
  parent_name text not null,
  email text not null,
  phone text,
  class_applied text,
  message text,
  created_at timestamptz not null default now()
);
create table if not exists public.job_applications (
  id bigint generated by default as identity primary key,
  applicant_name text not null,
  email text not null,
  phone text,
  position text not null,
  experience text,
  message text,
  created_at timestamptz not null default now()
);
alter table public.admissions enable row level security;
alter table public.job_applications enable row level security;
-- Only signed-in users whose Auth app_metadata role is admin can read records.
create policy "VKIS admins read admissions" on public.admissions for select to authenticated
using ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');
create policy "VKIS admins read job applications" on public.job_applications for select to authenticated
using ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');
